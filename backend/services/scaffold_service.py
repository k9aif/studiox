def _find_context_dir() -> Path:
    # Repo / container layout first; then the copy bundled into the k9x wheel
    # (k9x/_studio_app/context) for `pip install k9x`.
    repo = Path(__file__).parent.parent.parent / "context"
    if (repo / "CLAUDE.md").is_file():
        return repo
    try:
        import k9x  # noqa: WPS433
        bundled = Path(k9x.__file__).resolve().parent / "_studio_app" / "context"
        if (bundled / "CLAUDE.md").is_file():
            return bundled
    except ImportError:
        pass
    return repo


