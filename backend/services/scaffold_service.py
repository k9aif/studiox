def _slug(text: str) -> str:
    return re.sub(r"[^a-zA-Z0-9]+", "_", text or "").strip("_").lower()


def _first_word_slug(agent_label: str) -> str:
    """'AGN1 – Deterministic Rule Engine' -> 'agn1'; '*' (HITL rows have no
    single owning agent) -> 'generic', never an empty function-name segment."""
    token = agent_label.strip().split()[0] if agent_label.strip() else ""
    slug = re.sub(r"[^a-zA-Z0-9]+", "", token).lower()
    return slug or "generic"


def _docstring_safe(text: str) -> str:
    """Defend against free-text table content that happens to contain a
    literal triple-quote, which would otherwise prematurely close the
    generated docstring."""
    return (text or "").replace('"""', '\\"\\"\\"')


def _gen_eval_test_files(project: dict, app_name: str, app_folder: str, timestamp: str) -> dict[str, str]:
    """
    tests/evals/test_<category>.py — one pytest stub per eval-plan row,
    generated from Process Studio's companion Agent Evaluation Plan
    (-evals.md, see evals_service.py). Returns {} when no eval plan was
    staged (project["source_evals_rows"] empty) — this is additive, never
    replacing the existing generic tests/test_<app>.py stub.

    Every stub runs and PASSES out of the box (prints "<ID> - Hello
    World!", `assert True`) — deliberately not `pytest.mark.skip`-ed. A
    skipped suite hides collection problems silently; a green "Hello World"
    suite proves the harness itself works before the SA writes a single
    real assertion. This is a scaffold, not a finished test suite: the SA
    replaces each placeholder body with a real assertion against the Pass
    Criteria already sitting in that test's own docstring.

    Best-effort agent resolution: an eval row's "Step" (Process Studio's
    "ATSn" convention) is matched against the traceability matrix's
    process_id ("Task_n"/"Task_n_review") purely to NAME the real generated
    component in the docstring for the SA's convenience — never used to
    generate an import or a call in the test body itself, since a wrong
    guessed import would be worse than none.
    """
    rows = project.get("source_evals_rows") or []
    if not rows:
        return {}

    mapping_rows = build_mapping_document(project)["rows"]

    def resolve_component(step: str) -> Optional[str]:
        m = re.match(r"^ATS(\d+)$", (step or "").strip(), re.I)
        if not m:
            return None
        n = m.group(1)
        candidates = {f"Task_{n}", f"Task_{n}_review"}
        for r in mapping_rows:
            if r.get("process_id") in candidates:
                return f"{r.get('component')} ({r.get('component_kind', 'agent')})"
        return None

    by_category: dict[str, list[dict]] = {}
    for r in rows:
        by_category.setdefault(r.get("category") or "other", []).append(r)

    files: dict[str, str] = {}
    for category, category_rows in by_category.items():
        title = _EVAL_CATEGORY_TITLES.get(category, category.replace("_", " ").title())
        lines = [
            "# SPDX-License-Identifier: Apache-2.0",
            f"# Generated by k9x_studio on {timestamp} from Process Studio's Agent Evaluation Plan.",
            f"# Category: {title} — {len(category_rows)} case(s).",
            "#",
            "# Every test below runs and passes out of the box. Replace the placeholder",
            "# body with a real assertion per each test's own docstring (Scenario/Expected/",
            "# Pass Criteria) — see MANIFEST.md and implementation-plan.md for how this",
            "# category's agents map to what was actually generated.",
            "",
            "",
        ]
        seen_names: dict[str, int] = {}
        for r in category_rows:
            eid = r.get("id") or "UNKNOWN"
            base_name = f"test_{_slug(eid) or 'case'}_{_first_word_slug(r.get('agent', ''))}"
            # Guard against two rows colliding on the same generated name
            # (e.g. a missing/duplicate ID in the source doc) — append a
            # counter rather than silently overwriting one test with another.
            n = seen_names.get(base_name, 0)
            seen_names[base_name] = n + 1
            fn_name = base_name if n == 0 else f"{base_name}_{n}"

            component = resolve_component(r.get("step", ""))
            lines.append(f"def {fn_name}():")
            lines.append('    """')
            lines.append(f"    ID: {_docstring_safe(eid)}")
            lines.append(f"    Category: {title}")
            if r.get("agent"):
                agent_line = f"    Agent: {_docstring_safe(r['agent'])}"
                if component:
                    agent_line += f" -> {component}"
                lines.append(agent_line)
            if r.get("step"):
                lines.append(f"    Step: {_docstring_safe(r['step'])}")
            if r.get("severity"):
                lines.append(f"    Severity: {_docstring_safe(r['severity'])}")
            if r.get("scenario"):
                lines.append(f"    Scenario: {_docstring_safe(r['scenario'])}")
            if r.get("expected"):
                lines.append(f"    Expected: {_docstring_safe(r['expected'])}")
            if r.get("pass_criteria"):
                lines.append(f"    Pass Criteria: {_docstring_safe(r['pass_criteria'])}")
            coverage = r.get("framework_coverage")
            status = coverage.get("status") if coverage else None
            if coverage:
                details = coverage.get("details") or []
                if details:
                    # Adversarial entries carry gate/action (a Shield chain
                    # handler); Behavioral entries carry description only (a
                    # framework class/method, not a chain handler) — render
                    # whichever shape this row's details actually have.
                    names = ", ".join(
                        f"{c['name']} ({c['gate']}, {c['action']})" if "gate" in c else c["name"]
                        for c in details
                    )
                    verb = "already enforced" if status == "covered" else "partially enforced" if status == "partial" else "related"
                    lines.append(f"    Framework Coverage: {verb} — {names}.")
                    if coverage.get("note"):
                        lines.append(f"    Note: {_docstring_safe(coverage['note'])}")
                elif coverage.get("note"):
                    lines.append(f"    Framework Coverage: {_docstring_safe(coverage['note'])}")
            lines.append('    """')
            if status == "covered":
                lines.append("    # TODO: verify the framework mechanism above is enabled/configured for")
                lines.append("    # this deployment — it already implements this, no new logic needed here.")
            elif status == "partial":
                lines.append("    # TODO: the framework provides the escalation plumbing, but the domain")
                lines.append("    # judgment is still a stub (see the Note above) — implement it, then this")
                lines.append("    # test can assert against the Pass Criteria above.")
            else:
                lines.append("    # TODO: replace with a real assertion against the Pass Criteria above.")
            lines.append(f'    print("{eid} - Hello World!")')
            lines.append("    assert True")
            lines.append("")
            lines.append("")
        files[f"{app_folder}/tests/evals/test_{category}.py"] = "\n".join(lines)

    files[f"{app_folder}/tests/evals/__init__.py"] = f"# {app_name} — generated eval-plan test stubs\n"
    return files


