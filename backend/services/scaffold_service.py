def _gen_adapter_files(project: dict, app_name: str, timestamp: str) -> dict[str, str]:
    """One real .py file per canvas adapter, extending the matching
    Base*Adapter — replaces the old "documented only in ARCHITECTURE.md,
    no code generated" gap. Returns {path: content}, same shape as
    _gen_eval_test_files, merged into the zip alongside it."""
    files: dict[str, str] = {}
    for ad in project.get("adapters", []):
        atype = ad.get("adapter_type", "api_adapter")
        base_class, base_module, method_name, method_sig = _ADAPTER_BASE_CLASS.get(
            atype, _ADAPTER_BASE_CLASS["api_adapter"]
        )
        class_name = ad["name"]
        snake = to_snake(class_name)
        code = _render("adapter_base.py.j2", {
            "class_name": class_name,
            "app_name": app_name,
            "timestamp": timestamp,
            "base_class": base_class,
            "base_module": base_module,
            "method_name": method_name,
            "method_signature": method_sig,
            "description": ad.get("description") or _ADAPTER_LABEL.get(atype, atype),
        })
        files[f"adapters/src/{snake}.py"] = code
    return files


