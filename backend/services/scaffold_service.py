_MCP_TOOL_ID_PREFIX = re.compile(r"^([A-Z]+\d+)\s*[-‐-―−]\s*(.*)$")


def _mcp_tool_display_name(text: str) -> str:
    """'TOL1 – Retrieve Invoice Data' -> 'Retrieve Invoice Data' — same
    id-and-dash stripping as blueprint_service.py's _display_name(), kept
    local here to avoid a circular import (blueprint_service.py already
    imports to_pascal/to_snake FROM this module)."""
    m = _MCP_TOOL_ID_PREFIX.match((text or "").strip())
    return m.group(2).strip() if m else (text or "").strip()


