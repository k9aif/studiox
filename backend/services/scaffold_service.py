    # Ravi: "the column can be word wrapped. is this possible? if so,
    # please do it" — wrap_text on every data cell, top-aligned so a
    # wrapped multi-line cell doesn't center-float. Excel/Numbers both
    # auto-grow the row height for a wrapped cell on open; openpyxl itself
    # has no reliable way to compute that height in advance, so it's left
    # to the viewer rather than hardcoding a row height that would be
    # wrong for half the rows.
    wrap_alignment = Alignment(wrap_text=True, vertical="top")
    for row_idx, r in enumerate(rows, start=2):
        for col_idx, (key, _label) in enumerate(_TRACEABILITY_COLUMNS, start=1):
            cell = ws.cell(row=row_idx, column=col_idx, value=_export_cell_value(key, r.get(key)))
            cell.alignment = wrap_alignment

    # openpyxl has no built-in auto-fit — widest-cell-per-column is the
    # standard workaround — capped so a long free-text column (Governance,
    # HITL Touchpoint) doesn't blow out to one unreadable single-line width;
    # word-wrap (above) is what keeps a capped-width cell readable instead
    # of truncated.
    for col_idx, (key, label) in enumerate(_TRACEABILITY_COLUMNS, start=1):
        max_len = len(label)
        for r in rows:
            val = _export_cell_value(key, r.get(key))
            if val:
                max_len = max(max_len, len(str(val)))
        ws.column_dimensions[get_column_letter(col_idx)].width = min(max_len + 2, 60)

    ws.freeze_panes = "A2"
    if rows:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(_TRACEABILITY_COLUMNS))}{len(rows) + 1}"

    xlsx_buf = io.BytesIO()
    wb.save(xlsx_buf)
    return xlsx_buf.getvalue(), csv_text


