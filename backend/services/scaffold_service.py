def generate_class_diagram_puml(project: dict, app_name: str, app_folder: str, timestamp: str) -> str:
    """
    Build a high-level PlantUML class diagram for this project: the agents,
    squads and orchestrators the user designed, plus the K9-AIF ABB/OOB base
    classes they extend. Follows the conventions in puml/README.md
    (abstract vs concrete marking, package-per-squad grouping, `--|>` for
    inheritance, `..>` for "loads" dependencies).
    """
    agents = project.get("agents", [])
    squads = project.get("squads", [])
    orchestrators = project.get("orchestrators", [])

    def agent_base(agent_def: dict) -> str:
        t = agent_def.get("type", "BaseAgent")
        return t if t in _KNOWN_AGENT_BASE_TYPES else "BaseAgent"

    used_types = {agent_base(a) for a in agents}
    has_validation = "K9ValidationLoopAgent" in used_types
    has_critic = "K9CriticActorAgent" in used_types

    lines: list = []
    lines.append(f"@startuml {app_folder}_class_diagram")
    lines.append("")
    lines.append("' Generated by k9x Studio. k9x.ai")
    lines.append("")
    lines.append("skinparam classBackgroundColor #FAFAFA")
    lines.append("skinparam classBorderColor #AAAAAA")
    lines.append("skinparam ArrowColor #555555")
    lines.append("skinparam PackageBorderColor #CCCCCC")
    lines.append("skinparam PackageBackgroundColor #F5F7FF")
    lines.append("skinparam defaultFontSize 12")
    lines.append("hide circle")
    lines.append("")
    lines.append(f"title {app_name} - Class Diagram")
    lines.append("")

    # ── K9-AIF framework base classes (ABB / OOB) ───────────────────────
    lines.append('package "K9-AIF Framework (ABB / OOB)" #E8F5E9 {')
    lines.append("  abstract class BaseAgent {")
    lines.append("    + {abstract} execute(payload: dict) : dict")
    lines.append("  }")

    if has_validation:
        lines.append("  abstract class BaseValidationLoopAgent {")
        lines.append("    + execute(payload: dict) : dict")
        lines.append("    + {abstract} generate_hypothesis(loop_ctx)")
        lines.append("    + {abstract} run_validation(hypothesis, loop_ctx)")
        lines.append("    + {abstract} evaluate_observation(result, loop_ctx)")
        lines.append("    + {abstract} should_continue(obs, loop_ctx) : ValidationDisposition")
        lines.append("    + {abstract} finalize(loop_ctx) : ValidationLoopResult")
        lines.append("  }")
        lines.append("  class K9ValidationLoopAgent")
        lines.append("  BaseAgent <|-- BaseValidationLoopAgent")
        lines.append("  BaseValidationLoopAgent <|-- K9ValidationLoopAgent")

    if has_critic:
        lines.append("  abstract class BaseCriticActorAgent {")
        lines.append("    + execute(payload: dict) : dict")
        lines.append("    + {abstract} generate(ctx)")
        lines.append("    + {abstract} critique(draft, ctx) : dict")
        lines.append("    + {abstract} refine(draft, feedback, ctx)")
        lines.append("    + {abstract} should_accept(critique, ctx) : bool")
        lines.append("    + {abstract} finalize(ctx) : CriticActorResult")
        lines.append("  }")
        lines.append("  class K9CriticActorAgent")
        lines.append("  BaseAgent <|-- BaseCriticActorAgent")
        lines.append("  BaseCriticActorAgent <|-- K9CriticActorAgent")

    if squads:
        lines.append("  class BaseSquad {")
        lines.append("    + execute(payload: dict) : dict")
        lines.append("  }")

    if orchestrators:
        lines.append("  abstract class BaseOrchestrator {")
        lines.append("    + {abstract} execute_flow(payload: dict) : dict")
        lines.append("  }")

    lines.append("}")
    lines.append("")

    # ── agents, grouped by squad ─────────────────────────────────────────
    if agents:
        squad_agent_names = {a for sq in squads for a in sq.get("agents", [])}
        unassigned = [a for a in agents if a["name"] not in squad_agent_names]

        lines.append(f'package "{app_name} Agents" {{')
        for sq in squads:
            lines.append(f'  package "{sq["name"]}" {{')
            for agent_name in sq.get("agents", []):
                lines.append(f"    class {agent_name}")
            lines.append(f"    class {sq['name']}")
            lines.append("  }")
        if unassigned:
            if squads:
                lines.append('  package "Unassigned" {')
                for a in unassigned:
                    lines.append(f"    class {a['name']}")
                lines.append("  }")
            else:
                for a in unassigned:
                    lines.append(f"  class {a['name']}")
        lines.append("}")
        lines.append("")

        # agent → base class
        for a in agents:
            lines.append(f"{agent_base(a)} <|-- {a['name']}")
        lines.append("")

        # squad → BaseSquad, squad *-- agents
        for sq in squads:
            lines.append(f"BaseSquad <|-- {sq['name']}")
            for agent_name in sq.get("agents", []):
                lines.append(f"{sq['name']} *-- {agent_name}")
        if squads:
            lines.append("")

    # ── orchestrators ────────────────────────────────────────────────────
    if orchestrators:
        lines.append(f'package "{app_name} Orchestrators" {{')
        for o in orchestrators:
            lines.append(f"  class {o['name']}")
        lines.append("}")
        lines.append("")
        for o in orchestrators:
            lines.append(f"BaseOrchestrator <|-- {o['name']}")
            orch_squads = o.get("squads", [])
            if not orch_squads and o.get("squad"):
                orch_squads = [o["squad"]]
            parallel = o.get("parallel", False)
            rel_label = "executes (parallel)" if parallel else "loads"
            for sq_name in orch_squads:
                lines.append(f'{o["name"]} ..> {sq_name} : {rel_label}')
        lines.append("")

    # ── legend: what the arrows/lines mean ──────────────────────────────
    lines.append("legend bottom right")
    lines.append("|= Notation |= Meaning |")
    lines.append("| ──▷ | Inheritance (extends) |")
    lines.append("| ──◆ | Composition (owns) |")
    lines.append("| ╌╌> | Dependency (uses) |")
    lines.append("endlegend")
    lines.append("")

    lines.append("@enduml")
    return "\n".join(lines)


_PLANTUML_ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_"


def _plantuml_deflate_encode(puml_source: str) -> str:
    """PlantUML's "deflate + custom base64" URL encoding (stdlib zlib, no new deps) — far more compact than `~h<hex>`, which exceeds the server's GET length limit for non-trivial diagrams."""
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    data = compressor.compress(puml_source.encode("utf-8")) + compressor.flush()

    def encode6bit(b: int) -> str:
        return _PLANTUML_ALPHABET[b & 0x3F]

    out = []
    for i in range(0, len(data), 3):
        b1 = data[i]
        b2 = data[i + 1] if i + 1 < len(data) else 0
        b3 = data[i + 2] if i + 2 < len(data) else 0
        out.append(encode6bit(b1 >> 2))
        out.append(encode6bit(((b1 & 0x3) << 4) | (b2 >> 4)))
        out.append(encode6bit(((b2 & 0xF) << 2) | (b3 >> 6)))
        out.append(encode6bit(b3 & 0x3F))
    return "".join(out)


def render_puml_to_png(puml_source: str, timeout: int = 10) -> Optional[bytes]:
    """
    Render PlantUML source to PNG via the PlantUML server's deflate-encoded
    URL. Best-effort: returns None on any failure (offline, server
    unreachable, non-image response) so the scaffold ZIP always succeeds even
    without the rendered PNG.
    """
    try:
        url = f"{PLANTUML_SERVER}/png/{_plantuml_deflate_encode(puml_source)}"
        resp = requests.get(url, timeout=timeout)
        resp.raise_for_status()
        if resp.headers.get("Content-Type", "").startswith("image/png"):
            return resp.content
        return None
    except Exception:
        return None


