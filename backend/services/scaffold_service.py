K9AIF_VERSION = "1.12.4"


def _k9aif_requirement(project: dict) -> str:
    """`k9-aif[extras]==K9AIF_VERSION` -- `mcp` always (the generated MCP
    clients need it), plus the extras the project's platform selections
    need."""
    def picked(key: str) -> str:
        return " ".join(x for x in project.get(key, []) if x and x != "None").lower()

    extras = ["mcp"]
    messaging = picked("messaging_list")
    if any(k in messaging for k in ("kafka", "redpanda", "event streams")):
        extras.append("kafka")
    if "postgres" in picked("database_list"):
        extras.append("postgres")
    storage = picked("object_storage_list")
    if "cos" in storage or "cloud object storage" in storage:
        extras.append("ibm-cos")
    elif storage:
        extras.append("s3")
    return f"k9-aif[{','.join(extras)}]=={K9AIF_VERSION}"


def _gen_mcp_tool_files(project: dict, app_name: str, timestamp: str) -> dict[str, str]:
    """One real .py stub per blueprint MCP tool. Returns {path: content},
    same shape as _gen_adapter_files, merged into the zip alongside it."""
    files: dict[str, str] = {}
    for tool in project.get("mcp_tools", []):
        tool_name = _mcp_tool_display_name(tool.get("name", "")) or tool.get("tool_id") or "Tool"
        is_new_build = (tool.get("source") or "").strip().lower() == "new build"
        class_name = to_pascal(tool_name) + ("McpServer" if is_new_build else "McpAgent")
        snake = to_snake(class_name)
        template = "mcp_server_base.py.j2" if is_new_build else "mcp_agent_base.py.j2"
        code = _render(template, {
            "class_name": class_name,
            "app_name": app_name,
            "timestamp": timestamp,
            "tool_name": tool_name,
            "description": tool.get("description") or tool_name,
            "source": tool.get("source") or "Unspecified",
            "build_approach": tool.get("build_approach") or "not specified in blueprint",
            "authentication": tool.get("authentication") or "not specified in blueprint",
            "io_schema": tool.get("io_schema") or "not specified in blueprint",
            # Tool name on the MCP server: snake_case of the blueprint's tool
            # name (e.g. "Retrieve Invoice Data" -> retrieve_invoice_data),
            # overridable per agent via mcp_tool_name in its config.
            "mcp_tool_name": to_snake(tool_name),
        })
        files[f"mcp_tools/src/{snake}.py"] = code
    return files


