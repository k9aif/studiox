def to_snake(name: str) -> str:
    # Any non-alphanumeric character → underscore, not just ASCII space/hyphen —
    # a project name auto-derived from an uploaded filename can carry a literal
    # ".md" extension or a Unicode em-dash ("—", not matched by \s or \-), and
    # both need to disappear here since this also generates Python identifiers
    # (class/variable names) and the scaffold's own output folder name.
    s = re.sub(r"[^a-zA-Z0-9]+", "_", name.strip())
    s = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"_+", "_", s).lower().strip("_")  # collapse duplicates, normalise
    return s


def to_pascal(name: str) -> str:
    return "".join(p.capitalize() for p in to_snake(name).split("_"))


_env.filters["to_snake"] = to_snake
_env.filters["to_pascal"] = to_pascal


