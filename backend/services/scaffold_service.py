def _gen_eval_mapping_md(project: dict, timestamp: str) -> Optional[str]:
    """Ravi: "the Studio displays beautiful info in the Eval tab. but
    where is it documented in the output?" — the Evals tab's own
    category-grouped, k9x_Shield-coverage-annotated view (EvalsPanel.tsx's
    CategorySection) never had a corresponding output artifact; the
    coverage data only reached generated output as scattered comments
    across 81 separate tests/evals/*.py stub files. "simple. we have the
    data. just output it." — every field here already exists on each row
    in project["source_evals_rows"] (evals_service.py's parse_evals()),
    no new parsing needed. Mirrors the input->output k9x_ prefix
    convention already used for the traceability matrix, applied to the
    eval plan's own input document instead."""
    rows = project.get("source_evals_rows") or []
    if not rows:
        return None

    src_name = project.get("source_evals_filename") or "eval-plan.md"
    by_category: dict[str, list[dict]] = {}
    for r in rows:
        by_category.setdefault(r.get("category") or "uncategorized", []).append(r)

    lines = [
        f"# K9X Eval Coverage Mapping — {src_name}",
        "",
        f"**Input doc(s):** {_input_docs_summary(project)}  ",
        f"**Output doc:** this document — `k9x_{src_name}`",
        "",
        f"_Enriched by K9X Studio on {timestamp} — the **Framework Coverage** column shows which "
        f"k9x_Shield check (if any) already realizes each test case from the source Agent Evaluation "
        f"Plan, the same lookup shown live in the Studio's Evals tab. Everything else in this table is "
        f"the source plan's own content, unmodified._",
        "",
    ]
    for cat, title in _EVAL_CATEGORY_TITLES.items():
        cat_rows = by_category.pop(cat, None)
        if not cat_rows:
            continue
        lines.append(f"## {title}")
        lines.append("")
        lines.append("| ID | Agent | Step | Scenario | Expected | Pass Criteria | Severity | Framework Coverage |")
        lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
        for r in cat_rows:
            cells = [
                (r.get(k) or "").replace("|", "\\|").replace("\n", " ")
                for k in ("id", "agent", "step", "scenario", "expected", "pass_criteria", "severity")
            ]
            cells.append(_format_eval_coverage(r.get("framework_coverage")))
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")

    # Any category not in the known order (shouldn't happen — defensive only).
    for cat, cat_rows in by_category.items():
        lines.append(f"## {cat.replace('_', ' ').title()}")
        lines.append("")
        for r in cat_rows:
            lines.append(f"- {r.get('id', '')}: {r.get('scenario', '')}")
        lines.append("")

    lines.append(_doc_end_footer(timestamp))
    return "\n".join(lines)


