_SPECS = '''"""Agent specs from agents/yaml (the K9-AIF agent format), shared by this project's squad runtimes."""
from pathlib import Path
from typing import Any, Dict, List

import yaml

AGENTS_DIR = Path(__file__).resolve().parent.parent / "agents" / "yaml"


def specs_for(names: List[str]) -> Dict[str, Dict[str, Any]]:
    """The YAML spec of each named agent, keyed by name (read fresh, so YAML edits apply on restart)."""
    by_name: Dict[str, Dict[str, Any]] = {}
    for path in sorted(AGENTS_DIR.glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if data.get("name"):
            by_name[data["name"]] = data
    missing = [n for n in names if n not in by_name]
    if missing:
        raise ValueError(f"agent YAML missing for: {missing} (looked in {AGENTS_DIR})")
    return {n: by_name[n] for n in names}


def instructions_of(spec: Dict[str, Any]) -> str:
    """role, goal and instructions joined, the way K9-AIF agents read them."""
    parts = [str(spec.get(k, "")).strip() for k in ("role", "goal") if spec.get(k)]
    rules = spec.get("instructions")
    if isinstance(rules, list):
        parts.append("\\n".join(f"- {r}" for r in rules))
    elif rules:
        parts.append(str(rules).strip())
    return "\\n\\n".join(parts)
'''

