"""Generated runtimes for the agent framework a project's squads run on (one per project).

Native projects keep the existing squad layer. For any other framework, each squad gets a small module,
``runtimes/<squad>.py``, that builds that framework's own construct from the agents' YAML and returns K9-AIF's
adapter facade for it. The orchestrator still knows only squads (K9-DEC-002): it asks ``runtimes.<squad>.build()``
for the squad's facade and calls ``execute(payload)``. Same pattern as the framework's own examples
(weather_assist for CrewAI, weatherAssistLang for LangGraph) and the OpenAI example (k9x_openai_bedrock/openai).

| id                | a squad becomes                         | wrapped by                 | pip extra        |
|-------------------|-----------------------------------------|----------------------------|------------------|
| openai_agents     | entry agent + squad-mates as handoffs   | K9OpenAIAgentsAdapter      | openai-agents    |
| crewai            | a sequential Crew                       | K9CrewAIAdapter            | crewai           |
| langgraph         | a StateGraph, one node per agent        | K9LangGraphAdapter         | langgraph        |
| claude_agent_sdk  | one session, squad-mates as subagents   | K9ClaudeAgentSDKAdapter    | claude-agent-sdk |

Every module is structure the solution architect fills in (tools, prompts), the same "scaffold, not finished
implementation" contract as the rest of the generated project; but each one imports and runs as generated.
"""
